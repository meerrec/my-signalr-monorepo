/**
 * Reproducible OpenAPI contract pipeline.
 *
 * 1. Reads specs/rest.json and specs/signalr.json (or downloads them from
 *    REST_OPENAPI_URL / SIGNALR_OPENAPI_URL into .cache/ when those env vars are set).
 * 2. Merges both specs with openapi-merge-cli into .cache/merged-openapi.json.
 * 3. Generates packages/signalr-client/src/generated/rest.ts with swagger-typescript-api.
 * 4. Generates typed React hooks (rest-hooks.ts) from the merged operations.
 * 5. Generates hub contracts (hub-contracts.ts) from the x-signalr-hub extension.
 *
 * Run with: pnpm exec tsx scripts/generate-contracts.ts
 */
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const specsDir = path.join(repoRoot, 'specs');
const cacheDir = path.join(repoRoot, '.cache');
const stagedInputsDir = path.join(cacheDir, 'inputs');
const mergeConfigPath = path.join(cacheDir, 'openapi-merge.json');
const mergedSpecPath = path.join(cacheDir, 'merged-openapi.json');
const generatedDir = path.join(repoRoot, 'packages', 'signalr-client', 'src', 'generated');

const GENERATED_HEADER = [
  '// AUTO-GENERATED FILE. DO NOT EDIT.',
  '// Generated by scripts/generate-contracts.ts from .cache/merged-openapi.json.',
].join('\n');

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head', 'trace'] as const;
const IDENTIFIER_PATTERN = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

type JsonRecord = Record<string, unknown>;

interface PathParameter {
  name: string;
  tsType: string;
}

interface GeneratedParameter {
  name: string;
  type: string;
}

interface GeneratedMethod {
  group: string;
  methodName: string;
  params: GeneratedParameter[];
}

interface HookOperation {
  operationId: string;
  hookName: string;
  dataTypeName: string;
  pathParameters: PathParameter[];
  generated: GeneratedMethod;
  callArguments: string;
}

interface HubMethod {
  name: string;
  requestSchema: string;
  responseSchema: string | null;
}

interface HubEvent {
  name: string;
  payloadSchema: string;
}

interface HubMetadata {
  name: string;
  route: string;
  methods: HubMethod[];
  events: HubEvent[];
}

function isRecord(value: unknown): value is JsonRecord {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function asRecord(value: unknown, label: string): JsonRecord {
  if (!isRecord(value)) {
    throw new Error(`${label} must be an object`);
  }
  return value;
}

function asString(value: unknown, label: string): string {
  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`${label} must be a non-empty string`);
  }
  return value;
}

function toPascalCase(value: string): string {
  const parts = value.split(/[^A-Za-z0-9]+/).filter((part) => part.length > 0);
  if (parts.length === 0) {
    throw new Error(`Cannot convert "${value}" to PascalCase`);
  }
  return parts
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function toTypeIdentifier(value: string): string {
  const base = toPascalCase(value);
  const identifier = IDENTIFIER_PATTERN.test(base) ? base : `_${base.replace(/[^A-Za-z0-9_$]/g, '')}`;
  if (!IDENTIFIER_PATTERN.test(identifier)) {
    throw new Error(`Cannot derive a valid TypeScript identifier from "${value}"`);
  }
  return identifier;
}

function lowerFirst(value: string): string {
  return value.charAt(0).toLowerCase() + value.slice(1);
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

async function writeJson(filePath: string, value: unknown): Promise<void> {
  await writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

async function loadSpec(
  localPath: string,
  remoteUrl: string | undefined,
  label: string,
): Promise<JsonRecord> {
  let source: string;
  if (remoteUrl) {
    console.log(`[generate-contracts] downloading ${label} spec from ${remoteUrl}`);
    const response = await fetch(remoteUrl);
    if (!response.ok) {
      throw new Error(
        `Failed to download ${label} spec from ${remoteUrl}: ${response.status} ${response.statusText}`,
      );
    }
    source = await response.text();
  } else {
    source = await readFile(localPath, 'utf8');
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(source);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(`Failed to parse ${label} spec as JSON: ${reason}`);
  }
  return asRecord(parsed, `${label} spec`);
}

async function stageSpecs(): Promise<{ signalrSpec: JsonRecord }> {
  const restSpec = await loadSpec(
    path.join(specsDir, 'rest.json'),
    process.env.REST_OPENAPI_URL,
    'REST',
  );
  const signalrSpec = await loadSpec(
    path.join(specsDir, 'signalr.json'),
    process.env.SIGNALR_OPENAPI_URL,
    'SignalR',
  );

  // Both specs are staged into one directory so relative $refs between them
  // (for example ./rest.json#/components/schemas/ChatRoom) resolve regardless of
  // which spec was downloaded from a remote URL.
  await mkdir(stagedInputsDir, { recursive: true });
  await writeJson(path.join(stagedInputsDir, 'rest.json'), restSpec);
  await writeJson(path.join(stagedInputsDir, 'signalr.json'), signalrSpec);

  return { signalrSpec };
}

function resolvePackageBin(packageName: string, binName: string): string {
  const packageJsonPath = path.join(repoRoot, 'node_modules', packageName, 'package.json');
  const packageJson = JSON.parse(readFileSync(packageJsonPath, 'utf8')) as {
    bin?: string | Record<string, string>;
  };
  const relativeBin =
    typeof packageJson.bin === 'string' ? packageJson.bin : packageJson.bin?.[binName];
  if (!relativeBin) {
    throw new Error(`Cannot resolve bin "${binName}" of package "${packageName}"`);
  }
  return path.join(path.dirname(packageJsonPath), relativeBin);
}

function runNodeBin(packageName: string, binName: string, args: string[]): void {
  const binPath = resolvePackageBin(packageName, binName);
  const result = spawnSync(process.execPath, [binPath, ...args], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    const output = `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
    throw new Error(
      `${binName} exited with code ${String(result.status)}${output ? `\n${output}` : ''}`,
    );
  }
}

async function mergeSpecs(): Promise<JsonRecord> {
  await writeJson(mergeConfigPath, {
    inputs: [
      { inputFile: './inputs/rest.json' },
      { inputFile: './inputs/signalr.json' },
    ],
    output: './merged-openapi.json',
  });

  runNodeBin('openapi-merge-cli', 'openapi-merge-cli', ['--config', mergeConfigPath]);

  const mergedSource = await readFile(mergedSpecPath, 'utf8');
  let parsed: unknown;
  try {
    parsed = JSON.parse(mergedSource);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(`Merged OpenAPI spec is not valid JSON: ${reason}`);
  }
  return asRecord(parsed, 'merged OpenAPI spec');
}

function splitTopLevel(value: string): string[] {
  const parts: string[] = [];
  let current = '';
  let depth = 0;
  for (const char of value) {
    if (char === '<' || char === '{' || char === '(' || char === '[') {
      depth += 1;
    } else if (char === '>' || char === '}' || char === ')' || char === ']') {
      depth = Math.max(0, depth - 1);
    }

    if (char === ',' && depth === 0) {
      parts.push(current);
      current = '';
      continue;
    }
    current += char;
  }
  if (current.trim().length > 0) {
    parts.push(current);
  }
  return parts;
}

function parseGeneratedParameters(rawParameters: string): GeneratedParameter[] {
  const parameters: GeneratedParameter[] = [];
  for (const part of splitTopLevel(rawParameters)) {
    const trimmed = part.trim();
    if (trimmed.length === 0) {
      continue;
    }
    const colonIndex = trimmed.indexOf(':');
    if (colonIndex < 0) {
      continue;
    }
    const name = trimmed
      .slice(0, colonIndex)
      .trim()
      .replace(/\?$/, '');
    const type = trimmed
      .slice(colonIndex + 1)
      .trim()
      .replace(/\s*=\s*[\s\S]*$/, '')
      .trim();
    if (name.length > 0 && IDENTIFIER_PATTERN.test(name)) {
      parameters.push({ name, type });
    }
  }
  return parameters;
}

/**
 * swagger-typescript-api groups Api methods by the first path segment
 * (for example api.listRooms and hubs.negotiateChatHub). The grouping is read
 * from the generated source instead of being re-implemented here.
 */
function parseGeneratedApi(source: string): Map<string, GeneratedMethod> {
  const classStart = source.indexOf('export class Api<');
  if (classStart < 0) {
    throw new Error('Generated rest.ts does not contain "export class Api<"');
  }
  const classSource = source.slice(classStart);
  const methods = new Map<string, GeneratedMethod>();

  const groupPattern = /^ {2}([A-Za-z_$][\w$]*) = \{\n([\s\S]*?)^ {2}\};/gm;
  let groupMatch: RegExpExecArray | null;
  while ((groupMatch = groupPattern.exec(classSource)) !== null) {
    const group = groupMatch[1];
    const groupBody = groupMatch[2];
    if (!group || !groupBody) {
      continue;
    }

    const methodPattern = /^ {4}([A-Za-z_$][\w$]*): \(([\s\S]*?)\)\s*=>/gm;
    let methodMatch: RegExpExecArray | null;
    while ((methodMatch = methodPattern.exec(groupBody)) !== null) {
      const methodName = methodMatch[1];
      if (!methodName) {
        continue;
      }
      if (methods.has(methodName)) {
        throw new Error(`Generated Api contains duplicate method "${methodName}"`);
      }
      methods.set(methodName, {
        group,
        methodName,
        params: parseGeneratedParameters(methodMatch[2] ?? ''),
      });
    }
  }

  if (methods.size === 0) {
    throw new Error('Could not find any Api methods in the generated rest.ts');
  }
  return methods;
}

function resolveGeneratedMethod(
  methods: Map<string, GeneratedMethod>,
  operationId: string,
): GeneratedMethod {
  const candidates = [operationId, lowerFirst(operationId), lowerFirst(toPascalCase(operationId))];
  for (const candidate of candidates) {
    const method = methods.get(candidate);
    if (method) {
      return method;
    }
  }
  throw new Error(
    `Generated Api has no method for operationId "${operationId}". Known methods: ${[
      ...methods.keys(),
    ].join(', ')}`,
  );
}

function schemaToTsType(schema: unknown, context: string): string {
  if (!isRecord(schema)) {
    throw new Error(`Missing schema for ${context}`);
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    default:
      throw new Error(`Unsupported path parameter type "${String(schema.type)}" for ${context}`);
  }
}

function collectPathParameters(
  pathTemplate: string,
  pathLevelParameters: unknown[],
  operationParameters: unknown[],
): PathParameter[] {
  const parameterDefinitions = [...pathLevelParameters, ...operationParameters].filter(isRecord);
  const parameters: PathParameter[] = [];
  const templatePattern = /\{([^{}]+)\}/g;
  let match: RegExpExecArray | null;
  while ((match = templatePattern.exec(pathTemplate)) !== null) {
    const name = match[1];
    if (!name) {
      continue;
    }
    const definition = parameterDefinitions.find(
      (parameter) => parameter.in === 'path' && parameter.name === name,
    );
    if (!definition) {
      throw new Error(`Path parameter "${name}" of "${pathTemplate}" is not defined`);
    }
    parameters.push({
      name,
      tsType: schemaToTsType(definition.schema, `path parameter "${name}" of "${pathTemplate}"`),
    });
  }
  return parameters;
}

function buildCallArguments(
  pathParameters: PathParameter[],
  generated: GeneratedMethod,
  operationId: string,
): string {
  const valueParameters = generated.params.filter(
    (parameter) => parameter.name !== 'params' && !parameter.type.includes('RequestParams'),
  );

  if (pathParameters.length === 0) {
    if (valueParameters.length > 0) {
      throw new Error(
        `Operation "${operationId}" has unsupported parameters without path parameters: ${valueParameters
          .map((parameter) => `${parameter.name}: ${parameter.type}`)
          .join(', ')}`,
      );
    }
    return '';
  }

  const unknownParameters = valueParameters.filter(
    (parameter) => !pathParameters.some((pathParameter) => pathParameter.name === parameter.name),
  );

  if (unknownParameters.length > 0) {
    // Newer generators may group path params into a single object parameter.
    if (valueParameters.length === 1) {
      return `{ ${pathParameters.map((parameter) => parameter.name).join(', ')} }`;
    }
    throw new Error(
      `Unsupported Api method signature for operation "${operationId}" (${generated.group}.${
        generated.methodName
      }): ${generated.params.map((parameter) => `${parameter.name}: ${parameter.type}`).join(', ')}`,
    );
  }

  return valueParameters.map((parameter) => parameter.name).join(', ');
}

function buildHookOperations(
  mergedSpec: JsonRecord,
  generatedMethods: Map<string, GeneratedMethod>,
): HookOperation[] {
  const paths = asRecord(mergedSpec.paths, 'merged spec paths');
  const operations: HookOperation[] = [];
  const seenOperationIds = new Set<string>();

  for (const [pathTemplate, pathItemValue] of Object.entries(paths)) {
    if (!isRecord(pathItemValue)) {
      continue;
    }
    const pathLevelParameters = Array.isArray(pathItemValue.parameters)
      ? pathItemValue.parameters
      : [];

    for (const httpMethod of HTTP_METHODS) {
      const operation = pathItemValue[httpMethod];
      if (!isRecord(operation)) {
        continue;
      }
      const operationId = operation.operationId;
      if (typeof operationId !== 'string' || operationId.length === 0) {
        continue;
      }
      if (seenOperationIds.has(operationId)) {
        throw new Error(`Duplicate operationId "${operationId}" in merged spec`);
      }
      seenOperationIds.add(operationId);

      const operationParameters = Array.isArray(operation.parameters) ? operation.parameters : [];
      const pathParameters = collectPathParameters(
        pathTemplate,
        pathLevelParameters,
        operationParameters,
      );
      const generated = resolveGeneratedMethod(generatedMethods, operationId);
      operations.push({
        operationId,
        hookName: `use${toPascalCase(operationId)}`,
        dataTypeName: `${toPascalCase(operationId)}Data`,
        pathParameters,
        generated,
        callArguments: buildCallArguments(pathParameters, generated, operationId),
      });
    }
  }

  if (operations.length === 0) {
    throw new Error('Merged spec contains no operations with operationId');
  }

  operations.sort((left, right) => left.operationId.localeCompare(right.operationId));
  return operations;
}

function generateHooksSource(operations: HookOperation[]): string {
  const lines: string[] = [
    GENERATED_HEADER,
    '',
    "import { useCallback, useEffect, useMemo, useRef, useState } from 'react';",
    "import { Api } from './rest';",
    "import type { ApiConfig } from './rest';",
    '',
    'type ApiClient = Api<unknown>;',
    '',
  ];

  for (const operation of operations) {
    lines.push(
      `type ${operation.dataTypeName} = Awaited<ReturnType<ApiClient[${JSON.stringify(
        operation.generated.group,
      )}][${JSON.stringify(operation.generated.methodName)}]>>;`,
    );
  }

  lines.push(
    '',
    'export interface RestHookOptions {',
    '  immediate?: boolean;',
    '  baseUrl?: string;',
    '  api?: ApiClient;',
    '}',
    '',
    'export interface RestHookResult<T> {',
    '  data: T | null;',
    '  error: Error | null;',
    '  loading: boolean;',
    '  request: () => Promise<T | null>;',
    '  reset: () => void;',
    '}',
    '',
  );

  for (const operation of operations) {
    const signature = [
      ...operation.pathParameters.map(
        (parameter) => `${parameter.name}: ${parameter.tsType}`,
      ),
      'options: RestHookOptions = {}',
    ].join(', ');
    const dependencyList = ['api', ...operation.pathParameters.map((parameter) => parameter.name)];
    const callTarget = `api[${JSON.stringify(operation.generated.group)}][${JSON.stringify(
      operation.generated.methodName,
    )}]`;

    lines.push(
      `export function ${operation.hookName}(${signature}): RestHookResult<${operation.dataTypeName}> {`,
      '  const { immediate = true, baseUrl, api: providedApi } = options;',
      `  const [data, setData] = useState<${operation.dataTypeName} | null>(null);`,
      '  const [error, setError] = useState<Error | null>(null);',
      '  const [loading, setLoading] = useState(false);',
      '  const mountedRef = useRef(true);',
      '',
      '  useEffect(() => {',
      '    mountedRef.current = true;',
      '    return () => {',
      '      mountedRef.current = false;',
      '    };',
      '  }, []);',
      '',
      '  const api = useMemo(() => {',
      '    if (providedApi) {',
      '      return providedApi;',
      '    }',
      '    const config: ApiConfig = baseUrl === undefined ? {} : { baseUrl };',
      '    return new Api(config);',
      '  }, [providedApi, baseUrl]);',
      '',
      `  const request = useCallback(async (): Promise<${operation.dataTypeName} | null> => {`,
      '    if (mountedRef.current) {',
      '      setLoading(true);',
      '      setError(null);',
      '    }',
      '    try {',
      `      const result = await ${callTarget}(${operation.callArguments});`,
      '      if (mountedRef.current) {',
      '        setData(result);',
      '        setLoading(false);',
      '      }',
      '      return result;',
      '    } catch (caught) {',
      '      const nextError = caught instanceof Error ? caught : new Error(String(caught));',
      '      if (mountedRef.current) {',
      '        setError(nextError);',
      '        setLoading(false);',
      '      }',
      '      return null;',
      '    }',
      `  }, [${dependencyList.join(', ')}]);`,
      '',
      '  useEffect(() => {',
      '    if (immediate) {',
      '      void request();',
      '    }',
      '  }, [immediate, request]);',
      '',
      '  const reset = useCallback(() => {',
      '    setData(null);',
      '    setError(null);',
      '    setLoading(false);',
      '  }, []);',
      '',
      '  return { data, error, loading, request, reset };',
      '}',
      '',
    );
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

function readHubMetadata(mergedSpec: JsonRecord, signalrSpec: JsonRecord): HubMetadata {
  let hubSource = mergedSpec['x-signalr-hub'];
  if (!isRecord(hubSource)) {
    console.warn(
      '[generate-contracts] warning: x-signalr-hub is missing from the merged spec; falling back to specs/signalr.json',
    );
    hubSource = signalrSpec['x-signalr-hub'];
  }
  const hub = asRecord(hubSource, 'x-signalr-hub');

  const name = asString(hub.name, 'x-signalr-hub.name');
  const route = asString(hub.route, 'x-signalr-hub.route');

  const methodDefinitions = asRecord(hub.methods, 'x-signalr-hub.methods');
  const methods: HubMethod[] = Object.entries(methodDefinitions).map(([methodName, value]) => {
    if (!IDENTIFIER_PATTERN.test(methodName)) {
      throw new Error(`Hub method name "${methodName}" is not a valid identifier`);
    }
    const definition = asRecord(value, `x-signalr-hub.methods.${methodName}`);
    const requestSchema = asString(
      definition.request,
      `x-signalr-hub.methods.${methodName}.request`,
    );
    const responseValue = definition.response;
    const responseSchema =
      responseValue === null
        ? null
        : asString(responseValue, `x-signalr-hub.methods.${methodName}.response`);
    return { name: methodName, requestSchema, responseSchema };
  });

  const eventDefinitions = asRecord(hub.events, 'x-signalr-hub.events');
  const events: HubEvent[] = Object.entries(eventDefinitions).map(([eventName, value]) => {
    if (!IDENTIFIER_PATTERN.test(eventName)) {
      throw new Error(`Hub event name "${eventName}" is not a valid identifier`);
    }
    return {
      name: eventName,
      payloadSchema: asString(value, `x-signalr-hub.events.${eventName}`),
    };
  });

  return { name, route, methods, events };
}

function resolveSchemaTypeName(
  schemaName: string,
  schemas: JsonRecord,
  restSource: string,
): string {
  if (!(schemaName in schemas)) {
    throw new Error(`x-signalr-hub references missing schema "${schemaName}"`);
  }
  const typeName = toTypeIdentifier(schemaName);
  const exportPattern = new RegExp(
    `export (?:interface|type|enum|class) ${escapeRegExp(typeName)}\\b`,
  );
  if (!exportPattern.test(restSource)) {
    throw new Error(
      `Schema "${schemaName}" is not exported as "${typeName}" in the generated rest.ts`,
    );
  }
  return typeName;
}

function generateHubContractsSource(
  hub: HubMetadata,
  mergedSpec: JsonRecord,
  restSource: string,
): string {
  const components = asRecord(mergedSpec.components, 'merged spec components');
  const schemas = asRecord(components.schemas, 'merged spec components.schemas');

  const imports = new Set<string>();
  const resolvedMethods = hub.methods.map((method) => {
    const requestType = resolveSchemaTypeName(method.requestSchema, schemas, restSource);
    imports.add(requestType);
    const responseType =
      method.responseSchema === null
        ? 'void'
        : resolveSchemaTypeName(method.responseSchema, schemas, restSource);
    if (method.responseSchema !== null) {
      imports.add(responseType);
    }
    return { name: method.name, requestType, responseType };
  });
  const resolvedEvents = hub.events.map((event) => {
    const payloadType = resolveSchemaTypeName(event.payloadSchema, schemas, restSource);
    imports.add(payloadType);
    return { name: event.name, payloadType };
  });

  const lines: string[] = [GENERATED_HEADER, ''];

  const sortedImports = [...imports].sort((left, right) => left.localeCompare(right));
  if (sortedImports.length > 0) {
    lines.push(`import type { ${sortedImports.join(', ')} } from './rest';`, '');
  }

  lines.push('export interface HubMethodMap {');
  for (const method of resolvedMethods) {
    lines.push(`  ${method.name}: {`);
    lines.push(`    request: ${method.requestType};`);
    lines.push(`    response: ${method.responseType};`);
    lines.push('  };');
  }
  lines.push('}', '');

  lines.push('export interface HubEventMap {');
  for (const event of resolvedEvents) {
    lines.push(`  ${event.name}: ${event.payloadType};`);
  }
  lines.push('}', '');

  lines.push(
    'export type HubMethodName = keyof HubMethodMap;',
    'export type HubEventName = keyof HubEventMap;',
    '',
    'export const CHAT_HUB = {',
    `  name: ${JSON.stringify(hub.name)},`,
    `  route: ${JSON.stringify(hub.route)},`,
    '} as const;',
    '',
    'export const HUB_METHODS = [',
    ...resolvedMethods.map((method) => `  ${JSON.stringify(method.name)},`),
    '] as const;',
    '',
    'export const HUB_EVENTS = [',
    ...resolvedEvents.map((event) => `  ${JSON.stringify(event.name)},`),
    '] as const;',
  );

  return `${lines.join('\n')}\n`;
}

async function main(): Promise<void> {
  const { signalrSpec } = await stageSpecs();
  const mergedSpec = await mergeSpecs();

  if (!isRecord(mergedSpec['x-signalr-hub'])) {
    console.warn(
      '[generate-contracts] warning: x-signalr-hub did not survive the merge; it will be read from specs/signalr.json',
    );
  }

  await rm(generatedDir, { recursive: true, force: true });
  await mkdir(generatedDir, { recursive: true });

  runNodeBin('swagger-typescript-api', 'swagger-typescript-api', [
    'generate',
    '-p',
    mergedSpecPath,
    '-o',
    generatedDir,
    '-n',
    'rest.ts',
    // swagger-typescript-api 13.13.0 has an operator-precedence bug:
    // `args["http-client"] || args.axios ? AXIOS : FETCH`. Any non-empty value
    // selects axios, so an empty value is passed here to get the fetch client.
    '--http-client=',
    '--unwrap-response-data',
    '--type-only-imports',
    '--patch',
  ]);

  const restSource = await readFile(path.join(generatedDir, 'rest.ts'), 'utf8');
  const generatedMethods = parseGeneratedApi(restSource);
  const operations = buildHookOperations(mergedSpec, generatedMethods);
  await writeFile(path.join(generatedDir, 'rest-hooks.ts'), generateHooksSource(operations), 'utf8');

  const hub = readHubMetadata(mergedSpec, signalrSpec);
  const hubContractsSource = generateHubContractsSource(hub, mergedSpec, restSource);
  await writeFile(path.join(generatedDir, 'hub-contracts.ts'), hubContractsSource, 'utf8');

  console.log(
    `[generate-contracts] generated ${operations.length} hooks, ${hub.methods.length} hub methods and ${hub.events.length} hub events`,
  );
}

main().catch((error: unknown) => {
  const message = error instanceof Error ? error.stack ?? error.message : String(error);
  console.error(`[generate-contracts] failed: ${message}`);
  process.exitCode = 1;
});
